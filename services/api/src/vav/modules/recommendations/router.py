@router.get("/account/recommendation-history")
async def recommendation_history(
    request: Request,
    principal: AuthenticatedPrincipal = Depends(require_authenticated_user),
    session: AsyncSession = Depends(get_database_session),
) -> dict[str, Any]:
    rows = (
        await session.execute(
            text(
                "SELECT id, batch_number, batch_type, status, generated_size, created_at, expires_at "
                "FROM recommendation_batches WHERE user_id=:user_id ORDER BY batch_number DESC LIMIT 50"
            ),
            {"user_id": principal.user.id},
        )
    ).mappings()
    return success(
        {
            "batches": [
                {
                    "batch_id": str(row["id"]),
                    "batch_number": row["batch_number"],
                    "batch_type": row["batch_type"],
                    "status": row["status"],
                    "generated_size": row["generated_size"],
                    "created_at": row["created_at"],
                    "expires_at": row["expires_at"],
                }
                for row in rows
            ]
        },
        request_id_from_request(request),
    )


@router.get("/account/recommendation-transparency")
async def transparency(
    request: Request,
    principal: AuthenticatedPrincipal = Depends(require_authenticated_user),
    session: AsyncSession = Depends(get_database_session),
) -> dict[str, Any]:
    """Explain, for this member, what the engine used and what it did not.

    The page describes categories, the member's own settings and the platform
    defaults; it never shows another member's data or the internal weights of
    an individual recommendation.
    """
    criteria = await service.preference_criteria(session, principal.user.id)
    stated = {str(item["criterion_code"]) for item in criteria}
    tuning = await service.tuning_profile(session, principal.user.id)
    projection = await service.projection_for(session, principal.user.id)
    payload = service.projection_payload(projection) if projection else {}

    used: list[dict[str, Any]] = []
    for definition in FEATURE_DEFINITIONS:
        source = (
            "your_stated_preference" if definition.criterion_code in stated else "platform_default"
        )
        lookup = definition.criterion_code or definition.similarity_code
        known = bool(payload.get(lookup)) if lookup in payload else None
        used.append(
            {
                "feature_group": definition.feature_group,
                "feature_code": definition.feature_code,
                "source": source,
                "user_configurable": definition.user_configurable,
                "your_information_available": known,
            }
        )

    return success(
        {
            "data_categories_used": sorted(
                {definition.feature_group for definition in FEATURE_DEFINITIONS}
            ),
            "features": used,
            "hard_constraints_from_you": sorted(
                str(item["criterion_code"]) for item in criteria if item.get("hard_constraint")
            ),
            "never_used": [
                "photo_attractiveness",
                "ai_conversations",
                "counseling_records",
                "payment_history",
                "health_or_personality_inference",
            ],
            "behavioural_personalization_enabled": tuning["feedback_personalization_enabled"],
            "how_to_adjust": [
                "update_partner_preferences",
                "change_relaxable_criteria",
                "change_exploration_level",
                "disable_behavioural_personalization",
                "pause_recommendations",
            ],
        },
        request_id_from_request(request),
    )
