router = APIRouter()


def _item_dto(item: dict[str, Any]) -> dict[str, Any]:
    """The only shape a member ever receives for a recommendation item.

    Directional scores stay server-side: a member never learns what the other
    member's engine thought of them, and no compatibility percentage is shown.
    """
    return {
        "recommendation_item_id": str(item["id"]),
        "rank_position": item["rank_position"],
        "status": item["status"],
        "profile": item["visible_profile_snapshot"],
        "explanation": explanations.member_view(item["explanation_snapshot"] or {}),
        "available_from": item["available_from"],
        "expires_at": item["expires_at"],
    }


@router.get("/recommendations")
async def list_recommendations(
    request: Request,
    principal: AuthenticatedPrincipal = Depends(require_authenticated_user),
    session: AsyncSession = Depends(get_database_session),
) -> dict[str, Any]:
    service.enabled()
    user_id = principal.user.id
    entry = await service.pool_entry(session, user_id)
    settings_row = await service.user_settings(session, user_id)
    batch = await batches.active_batch(session, user_id)
    items = await batches.viewer_items(session, viewer_id=user_id) if batch else []

    payload: dict[str, Any] = {
        "eligible": bool(entry and entry["eligible"]),
        "ineligible_reason_codes": entry["eligibility_reasons"] if entry else ["no_pool_entry"],
        "recommendations_paused": settings_row["recommendations_paused"],
        "batch": None,
        "items": [_item_dto(item) for item in items],
        "empty_state": None,
    }
    if batch is not None:
        payload["batch"] = {
            "batch_id": str(batch["id"]),
            "batch_number": batch["batch_number"],
            "batch_type": batch["batch_type"],
            "status": batch["status"],
            "generated_size": batch["generated_size"],
            "expires_at": batch["expires_at"],
        }
    if not payload["items"]:
        report = service._jsonb(batch["generation_report"]) if batch else {}
        payload["empty_state"] = {
            "available_actions": list(cold_start.EMPTY_RESULT_ACTIONS),
            "most_restrictive_criteria": [
                {"criterion_code": code, "excluded_count": count}
                for code, count in sorted(
                    (report or {}).get("hard_constraint_failures", {}).items(),
                    key=lambda pair: (-pair[1], pair[0]),
                )[:5]
            ],
            "cold_start": (report or {}).get("cold_start"),
        }
    return success(payload, request_id_from_request(request))


@router.post("/recommendations/batches")
async def request_batch(
    request: Request,
    payload: BatchRequest,
    principal: AuthenticatedPrincipal = Depends(require_authenticated_user),
    session: AsyncSession = Depends(get_database_session),
) -> dict[str, Any]:
    """Request today's batch or a supplemental one.

    Repeat calls return the existing batch, so refreshing can never buy extra
    recommendations beyond the daily budget.
    """
    service.enabled()
    batch = await batches.generate_batch(
        session,
        principal.user.id,
        batch_type=payload.batch_type,
        requested_size=payload.requested_size,
    )
    await session.commit()
    return success(
        {
            "batch_id": str(batch["id"]),
            "batch_type": batch["batch_type"],
            "status": batch["status"],
            "generated_size": batch["generated_size"],
            "expires_at": batch["expires_at"],
        },
        request_id_from_request(request),
    )


@router.get("/recommendations/{item_id}")
async def get_recommendation(
    request: Request,
    item_id: UUID,
    principal: AuthenticatedPrincipal = Depends(require_authenticated_user),
    session: AsyncSession = Depends(get_database_session),
) -> dict[str, Any]:
    service.enabled()
    items = await batches.viewer_items(session, viewer_id=principal.user.id)
    for item in items:
        if item["id"] == item_id:
            return success(_item_dto(item), request_id_from_request(request))
    raise VavError("RECOMMENDATION_ITEM_NOT_FOUND", "Recommendation not found.", status_code=404)


